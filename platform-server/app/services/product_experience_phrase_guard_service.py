def _hits(text: str, phrases: tuple[str, ...]) -> list[str]:
    return [phrase for phrase in phrases if phrase and phrase in text]


def _hits_prefer_longer(text: str, phrases: tuple[str, ...]) -> list[str]:
    hits: list[str] = []
    for phrase in sorted((phrase for phrase in phrases if phrase and phrase in text), key=len, reverse=True):
        if any(phrase in existing for existing in hits):
            continue
        hits.append(phrase)
    return hits


def _current_temporal_context_hits(text: str) -> list[str]:
    hits: list[tuple[int, str]] = []
    for pattern in CURRENT_TEMPORAL_CONTEXT_PATTERNS:
        for match in pattern.finditer(text or ""):
            if _is_allowed_past_season_reference(match.group(0)):
                continue
            hits.append((match.start(), match.group(0)))
    ordered_hits: list[str] = []
    seen: set[str] = set()
    for _, hit in sorted(hits, key=lambda item: item[0]):
        if hit not in seen:
            ordered_hits.append(hit)
            seen.add(hit)
    return ordered_hits


def _filter_allowed_wangyue_time_event_hits(hits: list[str], *, text: str) -> list[str]:
    if not hits:
        return []
    filtered: list[str] = []
    for hit in hits:
        if _is_allowed_past_season_reference(text):
            continue
        filtered.append(hit)
    return filtered


def _is_allowed_past_season_reference(text: str) -> bool:
    return bool(
        re.search(
            r"(?:去年|前年|去年的|前年的|上个|上一个)"
            r"(?:春天|夏天|秋天|冬天|春季|夏季|秋季|冬季)",
            str(text or ""),
        )
    )


