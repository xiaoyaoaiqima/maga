def should_review_product_experience(plan: dict[str, Any] | None) -> bool:
    plan = plan or {}
    corpus = str(plan.get("corpus") or "")
    return (
        plan.get("rule_type") == "business_rule"
        and (
            str(plan.get("asset_key") or "").startswith("wangyue_")
            or "0705旺玥活动" in corpus
        )
    )


