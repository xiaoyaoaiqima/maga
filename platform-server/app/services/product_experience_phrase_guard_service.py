def _long_unpunctuated_segment_hits(text: str, *, threshold: int = 90) -> list[str]:
    hits: list[str] = []
    for segment in re.split(r"[，,。.!！？?；;\n\r]", str(text or "")):
        compact = re.sub(r"\s+", "", segment)
        if len(compact) >= threshold:
            hits.append(compact[:80])
    return hits


def _malformed_fragment_hits(text: str) -> list[str]:
    text = str(text or "")
    hits: list[str] = []
    if re.search(r'["“](?:title|body)["”]\s*[:：]', text, flags=re.IGNORECASE):
        hits.append("JSON字段残留")
    if text.lstrip().startswith(("{", "[")):
        hits.append("JSON结构残留")
    if "```json" in text or "```" in text:
        hits.append("Markdown代码块残留")
    if text.count("“") != text.count("”"):
        hits.append("中文引号不成对")
    if text.count("「") != text.count("」"):
        hits.append("中文引号不成对")
    if "中文引号不成对" in hits and re.search(r"[“「][^”」。！？；;]{18,}[。！？；;]", text):
        hits.append("半截对话")
    for match in re.finditer(r"(?<![A-Za-z])ta(?![A-Za-z])", text, flags=re.IGNORECASE):
        hits.append(f"中英文混写代词：{match.group(0)}")
    if "没看了一眼" in text:
        hits.append("没看了一眼")
    for phrase in (
        "家里挺旺玥",
        "完营养",
        "得挺利索",
        "现在，日常营养",
        "现在,日常营养",
        "娃快孩子了",
        "娃快孩子",
        "孩子快孩子了",
        "孩子快孩子",
        "娃刚满孩子",
        "孩子刚满孩子",
        "孩子半娃",
        "娃半娃",
        "娃快这个阶段了",
        "孩子快这个阶段了",
        "就是着",
        "跟着时候",
        "时候小变化",
    ):
        if phrase in text:
            hits.append(phrase)
    for match in re.finditer(r"(?:^|[，,。.!！？?；;\n\r])(得挺顺)", text):
        hits.append(match.group(1))
    tail = text.rstrip(" ，,。.!！？?；;\n\r")
    tail_match = re.search(
        r"(?:^|[，,。.!！？?；;\n\r])([^，,。.!！？?；;\n\r]{0,16}"
        r"(?:暂时|主要|主要是|因为|但是|不过|而且|所以|然后|只是|可能|感觉|其实|比如|就是|也算))$",
        tail,
    )
    if tail_match:
        hits.append(f"尾部残句：{tail_match.group(1)}")
    return hits


